/* =====================================================================
   HL7 demo: OPTIONAL shortcut. Create the 6 tables and load them straight
   from the pre-parsed CSVs (patients.csv, encounters.csv, diagnoses.csv,
   orders.csv, observations.csv, providers.csv).
   Produces the same tables as 01_load_and_parse_hl7.sql, so use one or the other.
   ===================================================================== */

CREATE DATABASE IF NOT EXISTS HL7_DEMO;
CREATE SCHEMA IF NOT EXISTS HL7_DEMO.CLINICAL;
USE SCHEMA HL7_DEMO.CLINICAL;

CREATE OR REPLACE FILE FORMAT HL7_TABLE_CSV_FORMAT
  TYPE = CSV
  SKIP_HEADER = 1
  FIELD_OPTIONALLY_ENCLOSED_BY = '"'
  EMPTY_FIELD_AS_NULL = TRUE
  TIMESTAMP_FORMAT = 'YYYY-MM-DD HH24:MI:SS'
  DATE_FORMAT = 'YYYY-MM-DD';

CREATE OR REPLACE STAGE HL7_TABLE_STAGE FILE_FORMAT = HL7_TABLE_CSV_FORMAT;
-- Upload the six CSVs to @HL7_TABLE_STAGE (Snowsight or SnowSQL PUT)

CREATE OR REPLACE TABLE PATIENTS (
  MRN             STRING,
  LAST_NAME       STRING,
  FIRST_NAME      STRING,
  MIDDLE_NAME     STRING,
  DATE_OF_BIRTH   DATE,
  SEX             STRING,
  RACE            STRING,
  ADDRESS_LINE1   STRING,
  CITY            STRING,
  STATE           STRING,
  ZIP             STRING,
  PHONE           STRING,
  MARITAL_STATUS  STRING,
  LAST_UPDATED    TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE ENCOUNTERS (
  VISIT_NUMBER                STRING,
  MRN                         STRING,
  PATIENT_CLASS               STRING,
  PATIENT_CLASS_DESC          STRING,
  ADMISSION_TYPE              STRING,
  ADMIT_SOURCE                STRING,
  HOSPITAL_SERVICE            STRING,
  POINT_OF_CARE               STRING,
  ROOM                        STRING,
  BED                         STRING,
  FACILITY                    STRING,
  ATTENDING_PROVIDER_ID       STRING,
  ADMIT_DATETIME              TIMESTAMP_NTZ,
  DISCHARGE_DATETIME          TIMESTAMP_NTZ,
  DISCHARGE_DISPOSITION       STRING,
  DISCHARGE_DISPOSITION_DESC  STRING,
  LENGTH_OF_STAY_DAYS         NUMBER,
  ENCOUNTER_STATUS            STRING,
  ADT_MESSAGE_COUNT           NUMBER
);

CREATE OR REPLACE TABLE DIAGNOSES (
  VISIT_NUMBER           STRING,
  MRN                    STRING,
  DIAGNOSIS_CODE         STRING,
  DIAGNOSIS_DESCRIPTION  STRING,
  CODING_SYSTEM          STRING,
  DIAGNOSIS_TYPE         STRING,
  DIAGNOSIS_TYPE_DESC    STRING,
  DIAGNOSIS_DATETIME     TIMESTAMP_NTZ,
  DIAGNOSIS_PRIORITY     NUMBER
);

CREATE OR REPLACE TABLE ORDERS (
  ORDER_ID              STRING,
  FILLER_ORDER_ID       STRING,
  VISIT_NUMBER          STRING,
  MRN                   STRING,
  ORDER_CODE            STRING,
  ORDER_NAME            STRING,
  CODING_SYSTEM         STRING,
  DIAGNOSTIC_SECTION    STRING,
  ORDERING_PROVIDER_ID  STRING,
  ORDER_DATETIME        TIMESTAMP_NTZ,
  RESULT_DATETIME       TIMESTAMP_NTZ,
  ORDER_STATUS          STRING
);

CREATE OR REPLACE TABLE OBSERVATIONS (
  MESSAGE_ID            STRING,
  ORDER_ID              STRING,
  VISIT_NUMBER          STRING,
  MRN                   STRING,
  SET_ID                NUMBER,
  VALUE_TYPE            STRING,
  OBSERVATION_CODE      STRING,
  OBSERVATION_NAME      STRING,
  CODING_SYSTEM         STRING,
  OBSERVATION_VALUE     STRING,
  NUMERIC_VALUE         FLOAT,
  UNITS                 STRING,
  REFERENCE_RANGE       STRING,
  ABNORMAL_FLAG         STRING,
  RESULT_STATUS         STRING,
  OBSERVATION_DATETIME  TIMESTAMP_NTZ
);

CREATE OR REPLACE TABLE PROVIDERS (
  PROVIDER_ID           STRING,
  LAST_NAME             STRING,
  FIRST_NAME            STRING,
  MIDDLE_INITIAL        STRING,
  DEGREE                STRING,
  ATTENDING_ENCOUNTERS  NUMBER,
  ORDERS_PLACED         NUMBER,
  FIRST_SEEN            TIMESTAMP_NTZ,
  LAST_SEEN             TIMESTAMP_NTZ
);

COPY INTO PATIENTS     FROM @HL7_TABLE_STAGE PATTERN = '.*patients[.]csv.*';
COPY INTO ENCOUNTERS   FROM @HL7_TABLE_STAGE PATTERN = '.*encounters[.]csv.*';
COPY INTO DIAGNOSES    FROM @HL7_TABLE_STAGE PATTERN = '.*diagnoses[.]csv.*';
COPY INTO ORDERS       FROM @HL7_TABLE_STAGE PATTERN = '.*orders[.]csv.*';
COPY INTO OBSERVATIONS FROM @HL7_TABLE_STAGE PATTERN = '.*observations[.]csv.*';
COPY INTO PROVIDERS    FROM @HL7_TABLE_STAGE PATTERN = '.*providers[.]csv.*';

-- Expected: 100 / 214 / 768 / 986 / 4,649 / 14
SELECT 'PATIENTS' AS TBL, COUNT(*) AS ROWS_LOADED FROM PATIENTS
UNION ALL SELECT 'ENCOUNTERS',   COUNT(*) FROM ENCOUNTERS
UNION ALL SELECT 'DIAGNOSES',    COUNT(*) FROM DIAGNOSES
UNION ALL SELECT 'ORDERS',       COUNT(*) FROM ORDERS
UNION ALL SELECT 'OBSERVATIONS', COUNT(*) FROM OBSERVATIONS
UNION ALL SELECT 'PROVIDERS',    COUNT(*) FROM PROVIDERS;
